# 2.Для s = "abcdefgh" получи:
# первый символ
# последний символ (двумя способами: через len и через отрицательный индекс)
# "cde"
# строку в обратном порядке
# каждый второй символ ("aceg")

s = "abcdefgh"
print(s[0])
print(s[len(s) - 1], s[-1])
print(s[s.find("cde"): s.find("cde")+3])
print(s[::-1])
print(s[::2])