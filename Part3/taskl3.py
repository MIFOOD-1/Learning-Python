# 3. Сортировка словарей,. В главе 8 мы выяснили, что словари являются неупорядочен
# ными последовательностями. Напишите цикл for, который выводит элементы 
# словаря в отсортированном порядке (по возрастанию). (Подсказка: применяйте 
# словарные методы keys и sort или более новую встроенную функцию sorted.)

D = dict(b= 100, a= 200, c=300)

for x in sorted(D): print(x, D[x])
for x in sorted(D.items()): print(x)
print([(x, y) for x, y in sorted(D.items())])
for x, y in sorted((x, y) for y, x in D.items()):
    print(y, x) 


